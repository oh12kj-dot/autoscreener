export const GLOSSARY: readonly GlossaryEntry[] = ENTRIES;

/**
 * 用語集に実在するidだけを `<Term id="...">` に渡せるようにする(28.18)。
 *
 * **これは `tsc` に拾わせるための型である。** 存在しないidを渡しても実行時には
 * 何も起きず、説明が付いているつもりの箇所が無言で普通のテキストになるだけ——
 * このアプリで最も気づきにくい壊れ方のひとつになる。`npm run build` が
 * 型チェックを含むので、ビルドの時点で必ず止まる。
 */
export type GlossaryId = (typeof ENTRIES)[number]["id"];

const BY_ID = new Map<string, GlossaryEntry>(ENTRIES.map((entry) => [entry.id, entry]));

export function lookup(id: string): GlossaryEntry | undefined {
  return BY_ID.get(id);
}

export function entriesByCategory(category: GlossaryCategory): GlossaryEntry[] {
  return GLOSSARY.filter((entry) => entry.category === category);
}

/** 用語集ページの検索。表記ゆれ・説明文も対象にする。 */
export function search(query: string): GlossaryEntry[] {
  const needle = query.trim().toLowerCase();
  if (!needle) return [...GLOSSARY];
  return GLOSSARY.filter((entry) =>
    [entry.term, entry.short, ...(entry.aliases ?? []), ...entry.body]
      .join(" ")
      .toLowerCase()
      .includes(needle),
  );
}
