def cached_system(rubric: str) -> list[dict[str, Any]]:
    """`SHARED_GUARDRAILS` + タスク別ルーブリックを、キャッシュ印つきで返す。

    ブロックを2つに分けているのは、`SHARED_GUARDRAILS` が全タスクで共通の
    前方一致プレフィックスになるようにするため。タスクを跨いでも前半だけは
    共有される。`cache_control` は最後のブロックに付ける——そこまでの全体が
    キャッシュ対象になる(前方一致なので、印より前は全部含まれる)。
    """
    return [
        {"type": "text", "text": SHARED_GUARDRAILS},
        {"type": "text", "text": rubric, "cache_control": {"type": "ephemeral"}},
    ]


def prompt_fingerprint(
    system: Sequence[dict[str, Any]], model: str, effort: str, provider: str = "anthropic"
) -> str:
    """指示文・モデル・effort(・プロバイダ)から決まる64桁の指紋。

    `llm_analyses` の一意キーの一部になる。ここが変われば別物として保存され、
    同じ銘柄に新旧2つの出力が並ぶ(古い方を消さないのは、後から
    「ルーブリックを変えて何が変わったか」を見るため)。

    `cache_control` は指示の中身ではなく配送方法なので、指紋から外す——
    キャッシュの有無で別物扱いになるのは筋が悪い。

    `provider` は既定(`anthropic`)のときだけ payload から省く——これまでに
    保存された Claude 由来の行の指紋を変えないため。別プロバイダを指定した
    ときだけ指紋に効き、同名モデルでも Claude の出力と混ざらない。
    """
    payload: dict[str, Any] = {
        "system": [{"type": b["type"], "text": b["text"]} for b in system],
        "model": model,
        "effort": effort,
    }
    if provider != "anthropic":
        payload["provider"] = provider
    encoded = json.dumps(payload, ensure_ascii=False, sort_keys=True).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()
